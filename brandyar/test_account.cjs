const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/account.js', 'utf8');
async function harness(data) {
  const root = {innerHTML:'', setAttribute(){}, querySelector(){return null;}, querySelectorAll(){return [];}};
  const listeners = {};
  const document = {querySelector:()=>root, body:{classList:{remove(){},toggle(){}}}, documentElement:{dataset:{}}, addEventListener:(key, fn)=>listeners[key]=fn};
  const context = vm.createContext({document, window:{addEventListener:(key,fn)=>listeners[key]=fn,confirm:()=>false}, location:{hash:'',pathname:'/account'}, history:{replaceState(){}}, localStorage:{getItem:()=>null}, fetch:async()=>({ok:true,status:200,json:async()=>({ok:true,data})})});
  vm.runInContext(source+';globalThis.center=AccountCenter;', context);
  await new Promise(resolve=>setImmediate(resolve));
  return {center:context.center,root,listeners,context};
}
(async()=>{
  const {center,root,listeners} = await harness({signedIn:true,csrf:'test',account:{name:'مریم نمونه',email:'user@example.test'},testCompleted:true,access:{status:'trial'}});
  assert.match(root.innerHTML,/نمای کلی حساب/);
  assert.match(root.innerHTML,/class="account-product-zone"/);
  assert.match(root.innerHTML,/class="account-support-zone"/);
  assert.doesNotMatch(root.innerHTML,/data-ai-generate|data-form="identity"/);
  assert.doesNotMatch(root.innerHTML,/<form/);
  assert.match(root.innerHTML,/aria-current="page"/);
  assert.match(root.innerHTML,/دسترسی آزمایشی/);
  assert.doesNotMatch(root.innerHTML,/completion-card/);
  assert.equal(center.completion({name:'نام'}).percent,100);
  assert.equal(center.completion({avatar:'optional'}).percent,0);
  assert.equal(center.initials('مریم نمونه'),'م ن');
  for (const status of ['active','trial']) assert.equal(center.accessInfo({testCompleted:true,access:{status}}).href,'/brandyar/dashboard');
  assert.equal(center.accessInfo({testCompleted:false,access:{status:'active'}}).testOnly,true);
  assert.equal(center.accessInfo({testCompleted:true,access:{status:'none'}}).action,'بررسی دسترسی');
  assert.equal(center.accessInfo({testCompleted:true,access:{status:'expired'}}).href,'/brandyar/plans');
  assert.ok(center.validation({name:'',email:'x',phone:'wrong'}).email);
  assert.equal(center.navigate('#information'),true);
  assert.match(root.innerHTML,/<form/);
  assert.match(root.innerHTML,/for="account-email">ایمیل /);
  assert.doesNotMatch(root.innerHTML,/ایمیل تماس/);
  assert.equal(center.dirty(),false);
  center.state.draft.name='ویرایش';
  assert.equal(center.dirty(),true);
  assert.equal(center.navigate('#security'),false);
  let blocked=false;
  listeners.beforeunload({preventDefault(){blocked=true;}});
  assert.equal(blocked,true);
  const escaped=await harness({signedIn:true,account:{name:'<img onerror=x>'},testCompleted:false});
  assert.match(escaped.root.innerHTML,/&lt;img onerror=x&gt;/);
  assert.doesNotMatch(escaped.root.innerHTML,/product-card/);
  const ended=await harness({signedIn:false});
  assert.match(ended.root.innerHTML,/نشست حساب پایان یافته/);
  const saving=await harness({signedIn:true,csrf:'test',account:{name:'قبلی'},testCompleted:true});
  saving.center.navigate('#information');
  const nodes=new Map();
  saving.root.querySelector=selector=>{if(!nodes.has(selector))nodes.set(selector,{textContent:'',setAttribute(){},focus(){},addEventListener(){}});return nodes.get(selector);};
  const form={querySelector:selector=>saving.root.querySelector(selector)};
  saving.center.state.draft.name='تازه';
  saving.context.fetch=async()=>({ok:false,status:503,json:async()=>({error:'ذخیره انجام نشد'})});
  await saving.center.save({preventDefault(){},target:form});
  assert.equal(saving.center.state.data.account.name,'قبلی');
  assert.equal(saving.center.state.draft.name,'تازه');
  assert.equal(saving.center.dirty(),true);
  assert.match(nodes.get('#save-message').textContent,/هنوز ثبت نشده/);
  saving.context.fetch=async()=>({ok:true,status:200,json:async()=>({ok:true,data:{account:{name:'تازه'}}})});
  await saving.center.save({preventDefault(){},target:form});
  assert.equal(saving.center.state.data.account.name,'تازه');
  assert.equal(saving.center.dirty(),false);
  assert.match(nodes.get('#save-message').textContent,/تغییرات حساب ثبت شد/);
  saving.center.state.draft.name='پس از انقضا';
  saving.context.fetch=async()=>({ok:false,status:401});
  await saving.center.save({preventDefault(){},target:form});
  assert.equal(saving.center.state.data,null);
  assert.match(saving.root.innerHTML,/نشست حساب پایان یافته/);
  console.log('Account rendering, validation, access, escaping, unsaved changes, save success/failure and session expiry passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
